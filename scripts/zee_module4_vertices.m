(* Self-contained native audit. Run from repository root. No external F16 files. *)
root=Directory[];
out=FileNameJoin[{root,"validation","module4","local"}];
If[!DirectoryQ[out],CreateDirectory[out,CreateIntermediateDirectories->True]];
report=<|"status"->"VERTEX_BLOCKED","mathematica_version"->$Version|>;
save[]:=Export[FileNameJoin[{out,"vertices.json"}],report,"RawJSON"];
save[];
package=FileNameJoin[{$HomeDirectory,".Mathematica","Applications","SARAH","SARAH.m"}];
If[!FileExistsQ[package],report["error"]="SARAH package absent";save[];Exit[2]];
Get[package];
SARAH[OutputDirectory]=FileNameJoin[{out,"sarah_output"}];
SARAH[InputDirectories]=Prepend[SARAH[InputDirectories],FileNameJoin[{root,"models","SARAH"}]];
SARAH`Start["ZeeTypeII"];
If[!TrueQ[SARAH`ModelLoaded]||TrueQ[SARAH`AbortStart],save[];Exit[3]];
report["sarah_version"]=ToString[SA`Version];
queries=Join[
 Table[{"photon_"<>ToString[q],{bar[q[{3}]],q[{3}],VP}},{q,{Fe,Fu,Fd}}],
 Flatten[Table[{"lepton_"<>ToString[{cp,a,b}],{bar[Fe[{a}]],Fe[{b}],If[cp==3,Ah[{2}],hh[{cp}]]}},{cp,3},{a,3},{b,3}],2],
 Flatten[Table[{"charged_minus_"<>ToString[{k,a,b}],{bar[Fe[{a}]],Fv[{b}],Hm[{k}]}},{k,{2,3}},{a,3},{b,3}],2],
 Flatten[Table[{"charged_plus_"<>ToString[{k,a,b}],{bar[Fv[{b}]],Fe[{a}],conj[Hm[{k}]]}},{k,{2,3}},{a,3},{b,3}],2],
 Flatten[Table[{"quark_"<>ToString[{cp,q}],{bar[q[{3}]],q[{3}],If[cp==3,Ah[{2}],hh[{cp}]]}},{cp,3},{q,{Fu,Fd}}],1],
 Table[{"WW_"<>ToString[k],{hh[{k}],VWm,conj[VWm]}},{k,2}],
 {{"WW_A",{Ah[{2}],VWm,conj[VWm]}}},
 Table[{"goldstone_"<>ToString[k],{hh[{k}],Hm[{1}],conj[Hm[{1}]]}},{k,2}],
 Flatten[Table[{"scalar_gauge_"<>ToString[{g,k,l}],{Hm[{k}],conj[Hm[{l}]],g}},{g,{VP,VZ}},{k,{2,3}},{l,{2,3}}],2],
 Flatten[Table[{"scalar_seagull_"<>ToString[{k,l}],{Hm[{k}],conj[Hm[{l}]],VP,VP}},{k,{2,3}},{l,{2,3}}],1],
 Flatten[Table[{"trilinear_"<>ToString[{cp,k,l}],{If[cp==3,Ah[{2}],hh[{cp}]],Hm[{k}],conj[Hm[{l}]]}},{cp,3},{k,{2,3}},{l,{2,3}}],2]
];
raw=Association[];
Do[vtx=CheckAbort[SARAH`Vertex[item[[2]],Eigenstates->EWSB],$Aborted];
 raw[item[[1]]]=vtx;
 Print["MODULE4_VERTEX ",item[[1]]," ",InputForm[vtx]],{item,queries}];
Export[FileNameJoin[{out,"vertices_raw.m"}],raw,"Package"];
report["raw"]=Map[ToString[#,InputForm]&,raw];
report["query_count"]=Length[queries];
report["status"]=If[FreeQ[Values[raw],$Aborted|SARAH`Vertex],"RAW_EXTRACTED_NOT_VALIDATED","VERTEX_BLOCKED"];
(* Optional numerical rules and independent assertions generated by Python. *)
If[FileExistsQ[FileNameJoin[{out,"witnesses.m"}]],Get[FileNameJoin[{out,"witnesses.m"}]]];
save[];
Print["MODULE4_VERTEX_STATUS ",report["status"]];
Exit[If[MemberQ[{"VERTEX_BLOCKED","VERTEX_CONFLICT"},report["status"]],4,0]];
