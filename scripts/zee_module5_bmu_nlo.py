def matching(mass, tanb, mt, mu=160, flip=False):
    with mp.workdps(70):
        x=(mp.mpf(mt)/mass)**2; u=1/mp.mpf(tanb)**2
        xy=mp.mpf(-1 if flip else 1)
        r1=x*u/2; r2=x*xy/2
        h=functions(x)
        def kernels(z):
            g=functions(z)
            return (mp.mpf(2)/3*g['g1']+functions(1/z)['g1']/z,
                    (mp.mpf(2)/3-z)*g['g2']-mp.mpf(1)/2,
                    g['g1'],g['g2'])
        k=kernels(x)
        c7=r1*k[0]+r2*k[1]; c8=r1*k[2]+r2*k[3]
        # BMU text after Eq.(29): all three products, including R2, fixed.
        d7=r1*mp.diff(lambda z:kernels(z)[0],x)+r2*mp.diff(lambda z:kernels(z)[1],x)
        d8=r1*mp.diff(lambda z:kernels(z)[2],x)+r2*mp.diff(lambda z:kernels(z)[3],x)
        log=mp.log((mp.mpf(mu)/mass)**2)
        c4=r1*(-mp.mpf(4)/3*h['f1']+h['f2'])
        c71=3*log*(mp.mpf(8)/3*x*d7+mp.mpf(40)/9*c7-mp.mpf(16)/27*c8)
        c71+=r1*((mp.mpf(4)/3*h['h1']+h['h3'])*mp.mpf(2)/3-(mp.mpf(4)/3*h['h4']+h['h6']))
        c71+=r2*((mp.mpf(4)/3*h['h7']+h['h9'])*mp.mpf(2)/3-(mp.mpf(4)/3*h['h10']+h['h12']))
        c81=3*log*(mp.mpf(8)/3*x*d8+mp.mpf(38)/9*c8)
        c81+=r1*(mp.mpf(16)/9*h['h13']+mp.mpf(4)/3*h['h16']+h['h18'])
        c81+=r2*(mp.mpf(16)/9*h['h19']+mp.mpf(4)/3*h['h22']+h['h24'])
        return dict(zip(('C7_LO','C8_LO','C4_NLO_raw','C7_NLO_raw','C8_NLO_raw'),map(float,(c7,c8,c4,c71,c81))))
